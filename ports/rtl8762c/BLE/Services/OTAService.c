// #include "Log.h"

#define LogLevel (Device.Consts.LogLevels.BluetoothLogLevel)

static T_SERVER_ID g_bas_srv_id;

static bool switch_to_ota_pending = false; /**< Is a bootloader switch to OTA mode pending? */

bool OTAService_isOTAPending()
{
    return switch_to_ota_pending;
}

/**
 * BT Profile service callback events are handled in this function
 * @note     Then the event handling function shall be called according to the
 *           service_id
 * @param    service_id  Profile service ID
 * @param    p_data      Pointer to callback data
 * @return   T_APP_RESULT, which indicates the function call is successful or
 * not
 * @retval   APP_RESULT_SUCCESS  Function run successfully
 * @retval   others              Function run failed, and return number
 * indicates the reason
 */
T_APP_RESULT OTAService_ProfileCB(T_SERVER_ID service_id, void* p_data)
{
    T_OTA_CALLBACK_DATA* p_ota_cb_data = (T_OTA_CALLBACK_DATA*)p_data;
    switch (p_ota_cb_data->msg_type) {
    case SERVICE_CALLBACK_TYPE_WRITE_CHAR_VALUE:
        if (OTA_WRITE_CHAR_VAL == p_ota_cb_data->msg_data.write.opcode && OTA_VALUE_ENTER == p_ota_cb_data->msg_data.write.u.value) {
            /** @todo: check if battery level is above 60 percent */
            // Log(LogLevel, Debug, "Preparing switch into OTA mode\n");
            /* prepare to enter OTA mode, before switch action, we should disconnect first. */
            switch_to_ota_pending = true;
            le_disconnect(0); /** @todo: better use
                        p_param->event_data.send_data_result.conn_id? */
        } else if (OTA_WRITE_IMAGE_COUNT_VAL == p_ota_cb_data->msg_data.write.opcode) {
            /* do nothing */
        }
        break;
    default:
        break;
    }

    return APP_RESULT_SUCCESS;
}

/**
 * @brief Add batter BLE service to the BLE stack database.
 *
 * @param[in]   p_func  Callback when service attribute was written to.
 * @return Service id generated by the BLE stack
 * @retval 0xFF Operation failure.
 * @retval others Service id assigned by stack.
 *
 */
bool OTAService_Add()
{
    g_bas_srv_id = ota_add_service(OTAService_ProfileCB);
    if (0xff == g_bas_srv_id) {
        // Log(LogLevel, Error, "config_ble_service_add_service: fail");
        return false;
    }
    // Logf(LogLevel, Debug, "OTA Service ID %d", g_bas_srv_id);
    return true;
}
